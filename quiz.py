# 题库：字典里套字典
题库 = {
    "Python的作者是谁？": {
        "选项": ["A. 比尔·盖茨", "B. 吉多·范罗苏姆", "C. 马克·扎克伯格", "D. 埃隆·马斯克"],
        "答案": "B"
    },
    "1 + 1 等于几？": {
        "选项": ["A. 1", "B. 2", "C. 3", "D. 4"],
        "答案": "B"
    },
    "中国的首都是哪里？": {
        "选项": ["A. 上海", "B. 广州", "C. 北京", "D. 深圳"],
        "答案": "C"
    },
    "Python中用什么打印文字？": {
        "选项": ["A. echo", "B. print", "C. console.log", "D. System.out"],
        "答案": "B"
    },
    "太阳从哪边升起？": {
        "选项": ["A. 西边", "B. 北边", "C. 南边", "D. 东边"],
        "答案": "D"
    }
}

print("=== 简易题库 ===")
print("共", len(题库), "道题，每题10分，满分", len(题库) * 10, "分！\n")

得分 = 0
题号 = 0

for 题目, 信息 in 题库.items():
    题号 += 1
    print("第", 题号, "题：", 题目)
    for 选项 in 信息["选项"]:
        print(选项)

    答案 = input("请选择答案（A/B/C/D）：")

    if 答案 == 信息["答案"]:
        print("✅ 回答正确！+10分\n")
        得分 += 10
    else:
        print("❌ 回答错误！正确答案是：", 信息["答案"], "\n")

print("=== 考试结束！===")
print("你的得分：", 得分, "分（共", len(题库) * 10, "分）")

if 得分 == len(题库) * 10:
    print("🌟 满分！太厉害了！")
elif 得分 >= len(题库) * 10 * 0.6:
    print("👍 及格了，继续加油！")
else:
    print("💪 不及格，多学学再来！")